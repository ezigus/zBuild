#!/usr/bin/env bash
# plugins/tool/pr-open/lib/body.sh — the PR description: what the PR is for
# (#2368, ADR-040). Sourced library: no set -euo pipefail.
#
# The body names the issue, the goal, each work item, the files changed and the
# test result. A finding that sent the change back was fixed before the PR; the
# review findings that did not — low ones, and ones already there before the
# change — are listed, each with its lens (#2433).

# Text from the plan is LLM-authored and lands in a GitHub PR body: strip ANSI,
# flatten control chars, and escape \ [ ] < > — the characters that inject
# (a link, raw HTML). Backticks, _ and * are left alone: they are prose.
_PR_OPEN_FINDING_JQ_DEFS='
    def esc: tostring
        | gsub("\\e\\[[0-9;?]*[A-Za-z~]"; "")
        | gsub("\\p{Cntrl}"; " ")
        | gsub("(?<c>[\\\\\\[\\]<>])"; "\\" + .c);
'

# _pr_open_review_findings <lens-result>... — one line per finding in the lens
# results, escaped like plan text.
_pr_open_review_findings() {
    local f
    for f in "$@"; do
        [[ -s "$f" ]] || continue
        jq -r "${_PR_OPEN_FINDING_JQ_DEFS}"'(.name // "a") as $n | (.findings // [])[]?
            | "- \($n | esc) lens, \(.severity | esc)\(if .introduced == false then ", already there before the change" else "" end): \(.message | esc) (\(.file | esc)\(if .line then ":\(.line)" else "" end))"' \
            "$f" 2>/dev/null || true
    done
}

# _pr_open_compose_body <issue> <plan_json> <test_outcome> <files_changed>
#   [unsettled_block] [forced_draft] [review_findings]
# #1799: when the run did not settle, its warning block comes first, right after
# the separator, and a forced draft carries zBuild's hidden marker at the end
# (lib/unsettled.sh). <files_changed> is one path per line.
_pr_open_compose_body() {
    local issue_num="$1" plan_json="$2" test_outcome="$3" files="$4"
    local unsettled="${5:-}" forced="${6:-false}" review="${7:-}" others=""
    local goal="" items="" changed="" lead="---" tail="" f n=0
    if [[ -n "$plan_json" && -f "$plan_json" ]]; then
        goal="$(jq -r "${_PR_OPEN_FINDING_JQ_DEFS}"'(.goal // .title // "") | esc' "$plan_json" 2>/dev/null || true)"
        items="$(jq -r "${_PR_OPEN_FINDING_JQ_DEFS}"'(.steps // .work_items // [])[]? | "- " + ((.description // .title // .id // "") | esc)' "$plan_json" 2>/dev/null || true)"
    fi
    while IFS= read -r f; do
        [[ -n "$f" ]] || continue
        n=$((n + 1))
        (( n <= 30 )) && changed+="- ${f}"$'\n'
    done <<< "$files"
    (( n > 30 )) && changed+="- … ($n files in all)"$'\n'
    [[ -n "$unsettled" ]] && lead+=$'\n'"${unsettled}"$'\n'
    [[ "$forced" == "true" ]] && tail=$'\n'"$(_pr_open_forced_draft_marker)"
    [[ -n "$review" ]] && others="**Other review findings** (none of them sends the change back):"$'\n'"${review}"$'\n\n'
    printf '%s\n\n%s\n**What this PR is for:** %s\n\n**Work items:**\n%s\n\n**Files changed:**\n%s\n**Tests:** %s\n\n%s%s%s' \
        "${issue_num:+Closes #${issue_num}}" "$lead" "${goal:-N/A}" \
        "${items:-- (none recorded)}" "${changed:-- (none)$'\n'}" "${test_outcome:-N/A}" \
        "$others" "Generated by zBuild automation." "$tail"
}
